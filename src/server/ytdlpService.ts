/**
 * Resolves redirect URLs for shortlinks (b23.tv, vt.tiktok.com, vm.tiktok.com, fb.watch, youtu.be)
 */
export async function resolveCanonicalUrl(rawUrl: string): Promise<string> {
  const cleanUrlMatch = rawUrl.match(/https?:\/\/[^\s]+/i);
  let targetUrl = cleanUrlMatch ? cleanUrlMatch[0] : rawUrl.trim();

  // 1. Resolve Bilibili b23.tv shortlink
  if (targetUrl.includes('b23.tv/')) {
    try {
      const res = await fetch(targetUrl, {
        method: 'GET',
        redirect: 'follow',
        headers: {
          'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
        },
        signal: AbortSignal.timeout(6000),
      });
      if (res.url && res.url !== targetUrl) {
        console.log(`[URL Resolver] Resolved b23.tv shortlink: ${targetUrl} -> ${res.url}`);
        targetUrl = res.url;
      }
    } catch (_) {}
  }
  // 2. Resolve TikTok shortlinks (vt.tiktok.com, vm.tiktok.com)
  else if (targetUrl.includes('vt.tiktok.com/') || targetUrl.includes('vm.tiktok.com/')) {
    try {
      const res = await fetch(targetUrl, {
        method: 'GET',
        redirect: 'follow',
        headers: {
          'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
        },
        signal: AbortSignal.timeout(6000),
      });
      if (res.url && res.url !== targetUrl) {
        console.log(`[URL Resolver] Resolved TikTok shortlink: ${targetUrl} -> ${res.url}`);
        targetUrl = res.url;
      }
    } catch (_) {}
  }

  return targetUrl;
}

/**
 * Direct Bilibili API extractor for Video Stream, Audio, and Metadata
 */
export async function extractBilibiliDirect(urlOrBvid: string): Promise<YtDlpExtractResult> {
  try {
    let bvid = '';
    const bvMatch = urlOrBvid.match(/BV1[a-zA-Z0-9]{9}|BV[a-zA-Z0-9]{10}/i);
    if (bvMatch) {
      bvid = bvMatch[0];
    } else {
      const resolved = await resolveCanonicalUrl(urlOrBvid);
      const m = resolved.match(/BV1[a-zA-Z0-9]{9}|BV[a-zA-Z0-9]{10}/i);
      if (m) bvid = m[0];
    }

    if (!bvid) {
      return {
        success: false,
        title: '',
        thumbnail: '',
        duration: 0,
        source: 'Bilibili',
        medias: [],
        error: 'Không tìm thấy mã video Bilibili (BVID) hợp lệ trong đường dẫn.',
      };
    }

    const cookieHeader = await getBilibiliCookieHeader();
    console.log(`[Bilibili Native Extractor] Fetching view info for BVID: ${bvid}...`);

    const viewRes = await fetch(`https://api.bilibili.com/x/web-interface/view?bvid=${bvid}`, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
        'Referer': 'https://www.bilibili.com/',
        'Cookie': cookieHeader,
      },
      signal: AbortSignal.timeout(7000),
    });

    if (!viewRes.ok) {
      return {
        success: false,
        title: '',
        thumbnail: '',
        duration: 0,
        source: 'Bilibili',
        medias: [],
        error: `Máy chủ Bilibili trả về mã lỗi HTTP ${viewRes.status}.`,
      };
    }

    const viewJson = await viewRes.json();
    if (viewJson.code !== 0 || !viewJson.data) {
      const errorMsg = viewJson.code === -404 || viewJson.message?.includes('木有') || viewJson.message?.includes('不存在')
        ? 'Video Bilibili này không tồn tại, đã bị tác giả xóa hoặc bị giới hạn riêng tư/khu vực.'
        : (viewJson.message || 'Không thể lấy thông tin video Bilibili.');
      return {
        success: false,
        title: '',
        thumbnail: '',
        duration: 0,
        source: 'Bilibili',
        medias: [],
        error: errorMsg,
      };
    }

    const vData = viewJson.data;
    const cid = vData.cid || (vData.pages?.[0]?.cid);
    const title = vData.title || `Bilibili Video (${bvid})`;
    let pic = vData.pic || '';
    if (pic.startsWith('//')) pic = `https:${pic}`;
    const duration = vData.duration || 0;
    const author = vData.owner?.name || undefined;
    const views = vData.stat?.view ? Number(vData.stat.view).toLocaleString('vi-VN') : undefined;

    // Fetch playurl streams
    const playUrlRes = await fetch(`https://api.bilibili.com/x/player/playurl?bvid=${bvid}&cid=${cid}&qn=80&fnval=0&fnver=0&fourk=1`, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
        'Referer': 'https://www.bilibili.com/',
        'Cookie': cookieHeader,
      },
      signal: AbortSignal.timeout(7000),
    });

    const medias: YtDlpMediaFormat[] = [];
    if (playUrlRes.ok) {
      const playJson = await playUrlRes.json();
      if (playJson.code === 0 && playJson.data?.durl) {
        const durls = playJson.data.durl;
        for (const item of durls) {
          if (item.url) {
            const qualityNum = playJson.data.quality || 64;
            let label = 'HD (720p)';
            if (qualityNum >= 80) label = 'Full HD (1080p)';
            else if (qualityNum === 64) label = 'HD (720p)';
            else if (qualityNum <= 32) label = 'SD (360p)';

            medias.push({
              quality: label,
              extension: 'mp4',
              url: item.url,
              directUrl: `/api/proxy-video?url=${encodeURIComponent(item.url)}`,
              size: formatBytes(item.size),
              isAudioOnly: false,
            });

            if (Array.isArray(item.backup_url)) {
              for (let i = 0; i < item.backup_url.length; i++) {
                const bUrl = item.backup_url[i];
                if (bUrl && medias.length < 3) {
                  medias.push({
                    quality: `${label} - Máy chủ dự phòng ${i + 1}`,
                    extension: 'mp4',
                    url: bUrl,
                    directUrl: `/api/proxy-video?url=${encodeURIComponent(bUrl)}`,
                    size: formatBytes(item.size),
                    isAudioOnly: false,
                  });
                }
              }
            }
          }
        }
      }
    }

    // Fetch official and AI subtitles
    const subtitles = await fetchBilibiliOfficialSubtitles(bvid);

    const primaryVideo = medias[0];
    return {
      success: true,
      title,
      thumbnail: pic,
      duration,
      durationFormatted: formatDurationSeconds(duration),
      source: 'Bilibili Direct API',
      author,
      views,
      medias,
      subtitles,
      videoUrl: primaryVideo?.url || '',
      directUrl: primaryVideo?.directUrl || primaryVideo?.url || '',
    };
  } catch (err: any) {
    return {
      success: false,
      title: '',
      thumbnail: '',
      duration: 0,
      source: 'Bilibili',
      medias: [],
      error: `Lỗi bóc tách Bilibili: ${err.message || err}`,
    };
  }
}

