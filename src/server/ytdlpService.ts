function formatBytes(bytes?: number): string | undefined {
  if (!bytes || isNaN(bytes) || bytes <= 0) return undefined;
  const mb = bytes / (1024 * 1024);
  if (mb >= 1024) {
    return `${(mb / 1024).toFixed(2).replace('.', ',')} GB`;
  }
  return `${mb.toFixed(1).replace('.', ',')} MB`;
}

function formatDurationSeconds(seconds?: number): string {
  if (!seconds || isNaN(seconds) || seconds <= 0) return '0:00';
  const mins = Math.floor(seconds / 60);
  const secs = Math.floor(seconds % 60);
  const hours = Math.floor(mins / 60);
  const remMins = mins % 60;
  if (hours > 0) {
    return `${hours}:${remMins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
  }
  return `${mins}:${secs.toString().padStart(2, '0')}`;
}

function formatTimeSrt(seconds: number): string {
  if (isNaN(seconds) || seconds < 0) seconds = 0;
  const pad = (num: number, size = 2) => num.toString().padStart(size, '0');
  const hrs = Math.floor(seconds / 3600);
  const mins = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  const ms = Math.floor((seconds % 1) * 1000);
  return `${pad(hrs)}:${pad(mins)}:${pad(secs)},${pad(ms, 3)}`;
}

/**
 * Converts various subtitle formats (Bilibili JSON, WebVTT, YouTube XML/TTML, Danmaku XML) into clean SRT text
 */
export function convertSubtitleToSrt(rawContent: string): string {
  if (!rawContent || !rawContent.trim()) return '';

  const trimmed = rawContent.trim();

  // 1. Check if Bilibili JSON Subtitle format { font_size, body: [ { from, to, content } ] }
  if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
    try {
      const parsed = JSON.parse(trimmed);
      const body = parsed.body || parsed.data?.body || (Array.isArray(parsed) ? parsed : null);
      if (Array.isArray(body) && body.length > 0) {
        return body
          .map((item: any, index: number) => {
            const startSec = typeof item.from === 'number' ? item.from : parseFloat(item.from || '0');
            const endSec = typeof item.to === 'number' ? item.to : parseFloat(item.to || (startSec + 2).toString());
            const text = (item.content || '').trim();
            if (!text) return '';
            return `${index + 1}\n${formatTimeSrt(startSec)} --> ${formatTimeSrt(endSec)}\n${text}\n`;
          })
          .filter(Boolean)
          .join('\n');
      }
    } catch (_) {}
  }

  // 2. Check if YouTube JSON3 format
  if (trimmed.startsWith('{') && trimmed.includes('"events"')) {
    try {
      const parsed = JSON.parse(trimmed);
      if (Array.isArray(parsed.events)) {
        let srtIndex = 1;
        const cues: string[] = [];
        for (const ev of parsed.events) {
          if (!ev.segs || !Array.isArray(ev.segs)) continue;
          const text = ev.segs.map((s: any) => s.utf8 || '').join('').trim();
          if (!text || text === '\n') continue;
          const startSec = (ev.tStartMs || 0) / 1000;
          const durSec = (ev.dDurationMs || 2000) / 1000;
          const endSec = startSec + durSec;
          cues.push(`${srtIndex++}\n${formatTimeSrt(startSec)} --> ${formatTimeSrt(endSec)}\n${text}\n`);
        }
        if (cues.length > 0) return cues.join('\n');
      }
    } catch (_) {}
  }

  // 3. Check if WebVTT
  if (trimmed.startsWith('WEBVTT') || trimmed.includes('-->')) {
    // Convert WebVTT timestamps (00:00:00.000) to SRT timestamps (00:00:00,000)
    let srtText = trimmed
      .replace(/^WEBVTT[^\n]*\n+/i, '')
      .replace(/(\d{2}:\d{2}:\d{2})\.(\d{3})/g, '$1,$2')
      .replace(/(\d{2}:\d{2})\.(\d{3})/g, '00:$1,$2');
    return srtText;
  }

  // 4. Check if YouTube XML / TTML (<text start="1.2" dur="3.4">...</text>)
  if (trimmed.includes('<text') || trimmed.includes('<p begin=')) {
    const textMatches = [...trimmed.matchAll(/<text[^>]*start="([^"]+)"[^>]*(?:dur="([^"]+)")?[^>]*>([\s\S]*?)<\/text>/gi)];
    if (textMatches.length > 0) {
      return textMatches
        .map((m, idx) => {
          const startSec = parseFloat(m[1] || '0');
          const durSec = parseFloat(m[2] || '2.0');
          const endSec = startSec + durSec;
          const text = m[3]
            .replace(/&amp;/g, '&')
            .replace(/&lt;/g, '<')
            .replace(/&gt;/g, '>')
            .replace(/&quot;/g, '"')
            .replace(/&#39;/g, "'")
            .replace(/<[^>]+>/g, '')
            .trim();
          if (!text) return '';
          return `${idx + 1}\n${formatTimeSrt(startSec)} --> ${formatTimeSrt(endSec)}\n${text}\n`;
        })
        .filter(Boolean)
        .join('\n');
    }
  }

// 5. Check if Bilibili Danmaku XML (<d p="12.345,1,25,16777215,...">Comment</d>)
  if (trimmed.includes('<d p=')) {
    const dMatches = [...trimmed.matchAll(/<d\s+p="([^"]+)">([\s\S]*?)<\/d>/gi)];
    if (dMatches.length > 0) {
      let idx = 1;
      const cues: string[] = [];
      for (const m of dMatches) {
        const pParams = m[1].split(',');
        const startSec = parseFloat(pParams[0] || '0');
        const durSec = 3.5;
        const endSec = startSec + durSec;
        const text = m[2]
          .replace(/&amp;/g, '&')
          .replace(/&lt;/g, '<')
          .replace(/&gt;/g, '>')
          .replace(/&quot;/g, '"')
          .replace(/&#39;/g, "'")
          .trim();
        if (!text) continue;
        cues.push(`${idx++}\n${formatTimeSrt(startSec)} --> ${formatTimeSrt(endSec)}\n${text}\n`);
      }
      if (cues.length > 0) return cues.join('\n');
    }
  }

  return trimmed;
}

