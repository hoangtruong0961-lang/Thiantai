/**
 * Finds the best available path for yt-dlp binary
 */
export async function ensureYtDlpBinary(): Promise<string> {
  const customPath = process.env.YTDLP_PATH;
  if (customPath && fs.existsSync(customPath)) {
    try {
      fs.chmodSync(customPath, 0o755);
    } catch (_) {}
    return customPath;
  }

  const localBinLinux = path.join(process.cwd(), 'bin', 'yt-dlp_linux');
  if (fs.existsSync(localBinLinux)) {
    try {
      const stat = fs.statSync(localBinLinux);
      if (stat.size > 5000000) {
        fs.chmodSync(localBinLinux, 0o755);
        return localBinLinux;
      }
    } catch (_) {}
  }

  const localBin = path.join(process.cwd(), 'bin', 'yt-dlp');
  if (fs.existsSync(localBin)) {
    try {
      const stat = fs.statSync(localBin);
      if (stat.size > 1000000) {
        fs.chmodSync(localBin, 0o755);
        return localBin;
      }
    } catch (_) {}
  }

  const localBinWin = path.join(process.cwd(), 'bin', 'yt-dlp.exe');
  if (fs.existsSync(localBinWin)) {
    return localBinWin;
  }

  const usrLocalBin = '/usr/local/bin/yt-dlp';
  if (fs.existsSync(usrLocalBin)) {
    return usrLocalBin;
  }

  // Attempt auto-downloading yt-dlp_linux or yt-dlp if not found
  try {
    const binDir = path.join(process.cwd(), 'bin');
    fs.mkdirSync(binDir, { recursive: true });
    console.log('[yt-dlp Service] Downloading official yt-dlp release binary...');
    const dlRes = await fetch('https://github.com/yt-dlp/yt-dlp/releases/latest/download/yt-dlp_linux');
    if (dlRes.ok) {
      const buf = Buffer.from(await dlRes.arrayBuffer());
      fs.writeFileSync(localBinLinux, buf);
      fs.chmodSync(localBinLinux, 0o755);
      console.log('[yt-dlp Service] Successfully installed yt-dlp_linux binary.');
      return localBinLinux;
    }
  } catch (dlErr: any) {
    console.warn('[yt-dlp Service] Auto-download failed:', dlErr?.message || dlErr);
  }

  return 'yt-dlp';
}

